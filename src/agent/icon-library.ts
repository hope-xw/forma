function normalizeName(value: string) {
  return value
    .trim()
    .replace(/([a-z\d])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d+)$/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase()
    .replace(/^lucide-/, "")
    .replace(/-icon$/, "");
}

