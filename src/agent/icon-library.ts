// Only short, near-matching names are candidates for spelling suggestions.
function spellingDistance(query: string, name: string) {
  if (query.length < 3 || Math.abs(query.length - name.length) > 2)
    return Infinity;
  let row = Array.from({ length: name.length + 1 }, (_, i) => i);
  for (let i = 0; i < query.length; i++) {
    const next = [i + 1];
    for (let j = 0; j < name.length; j++) {
      next.push(
        Math.min(
          next[j] + 1,
          row[j + 1] + 1,
          row[j] + Number(query[i] !== name[j]),
        ),
      );
    }
    row = next;
  }
  return row[name.length];
}

export function searchIcons(
  query = "",
  limit = 24,
): Array<{ name: string; tags: string[] }> {
  const term = normalizeName(query);
  const resolved = resolveIconName(term);
  const words = term.split("-").filter(Boolean);
  const ranked = [];
  for (const { name, tags } of catalog.values()) {
    let score = 0;
    if (name === resolved) score = 100;
    else if (!term) score = 1;
    else if (name.startsWith(term)) score = 80;
    else if (tags.includes(term)) score = 70;
    else if (name.includes(term)) score = 60;
    else if (
      words.length &&
      words.every((w) => tags.some((t) => t.includes(w)))
    )
      score = 50;
    else {
      const distance = spellingDistance(term, name);
      if (distance <= 2) score = 10 - distance;
    }
    if (score) ranked.push({ name, tags, score });
  }
  return ranked
    .sort((a, b) => b.score - a.score)
    .slice(0, Math.max(0, limit))
    .map(({ name, tags }) => ({ name, tags: [...tags] }));
}

function primitivePath([tag, attrs]: IconPrimitive): string | undefined {
  const number = (key: string, fallback = 0) => {
    const v = attrs[key];
    if (v === undefined) return fallback;
    const value = String(v).trim();
    return /^[+-]?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?(?:px)?$/i.test(value)
      ? Number(value.replace(/px$/i, ""))
      : NaN;
  };
  switch (tag) {
    case "path": {
      const d = String(attrs.d ?? "").trim();
      if (
        !d ||
        d.length > 100000 ||
        !/^[Mm][MmZzLlHhVvCcSsQqTtAaEe0-9.,+\s-]*$/.test(d)
      )
        return;
      const path = svgpath(d);
      // svgpath exposes parser errors on the instance, outside its type declarations.
      if (
        (path as typeof path & { err: string }).err ||
        /Infinity|NaN/.test(path.toString())
      )
        return;
      return d;
    }
    case "circle":
    case "ellipse": {
      const cx = number("cx"),
        cy = number("cy");
      const rx = number(tag === "circle" ? "r" : "rx"),
        ry = tag === "circle" ? rx : number("ry");
      if (rx <= 0 || ry <= 0) return;
      return `M ${cx - rx} ${cy} a ${rx} ${ry} 0 1 0 ${2 * rx} 0 a ${rx} ${ry} 0 1 0 ${-2 * rx} 0 Z`;
    }
    case "rect": {
      const x = number("x"),
        y = number("y"),
        w = number("width"),
        h = number("height");
      if (w <= 0 || h <= 0) return;
      const rx = Math.min(w / 2, number("rx", number("ry"))),
        ry = Math.min(h / 2, number("ry", number("rx")));
      if (!Number.isFinite(rx) || !Number.isFinite(ry) || rx < 0 || ry < 0)
        return;
      if (!rx || !ry) return `M ${x} ${y} h ${w} v ${h} h ${-w} Z`;
      const arc = `a ${rx} ${ry} 0 0 1`;
      return `M ${x + rx} ${y} h ${w - 2 * rx} ${arc} ${rx} ${ry} v ${h - 2 * ry} ${arc} ${-rx} ${ry} h ${2 * rx - w} ${arc} ${-rx} ${-ry} v ${2 * ry - h} ${arc} ${rx} ${-ry} Z`;
    }
    case "line":
      return `M ${number("x1")} ${number("y1")} L ${number("x2")} ${number("y2")}`;
    case "polyline":
    case "polygon": {
      const points = String(attrs.points ?? "")
        .trim()
        .split(/[\s,]+/);
      if (points.length < (tag === "polygon" ? 6 : 4) || points.length % 2)
        return;
      const coords = points.map((v) => (v ? Number(v) : NaN));
      return `M ${coords.join(" ")}${tag === "polygon" ? " Z" : ""}`;
    }
  }
}

export function iconPrimitivesToSvgPaths(
  primitives: IconPrimitive[],
): string[] {
  return primitives.flatMap((primitive) => {
    const d = primitivePath(primitive);
    return d && d.length <= 100000 && !/NaN|Infinity/.test(d) ? [d] : [];
  });
}

