export function publishedReleaseNotes(updates: readonly ReleaseUpdate[]) {
  const published = [];
  let pending: string[] = [];
  for (const { version, date, title, summary, highlights } of updates) {
    const items = [summary, ...(highlights ?? [])]
      .map((item) => item.trim())
      .filter(Boolean);
    if (title) {
      published.push({ version, date, title, changes: [...items, ...pending] });
      pending = [];
    } else {
      pending.push(...items);
    }
  }
  return published.reverse();
}

export const releaseNotes = publishedReleaseNotes(releaseUpdates);
